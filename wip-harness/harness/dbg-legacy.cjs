const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
const E = require('./e2e.cjs');
(async () => {
  const browser = await chromium.launch({ args: E.H.launchArgs() });
  const { page, errors } = await E.newPage(browser);
  page.on('console', m => console.log('[c]', m.type(), m.text().slice(0, 200)));
  await page.goto('https://app.test/');
  await page.waitForSelector('.frame-card', { timeout: 20000 });
  await page.click('#tabTryOnBtn');
  await page.setInputFiles('#fileInput', path.join(E.H.S, 'assets/business-person.png'));
  await E.sleep(4000);
  console.log('canvas display', await page.$eval('#canvas', e => getComputedStyle(e).display), 'banner', await page.$eval('#calibBanner', e => e.textContent + '|' + getComputedStyle(e).display));
  await page.click('#retakeBtn');
  await page.setInputFiles('#fileInput', path.join(E.H.S, 'assets/business-person.png'));
  await E.sleep(3000);
  console.log('after re-upload canvas display', await page.$eval('#canvas', e => getComputedStyle(e).display));
  await page.click('#tabBrowseBtn'); await page.click('.frame-card[data-id="f4"] .frame-card-tryon'); await page.click('#goTryOnBtn');
  await E.sleep(2000);
  console.log('ar?', await page.evaluate(() => !!document.querySelector('#photoStage .ar-canvas')), 'errors', errors);
  await (await page.$('#viewport')).screenshot({ path: path.join(E.OUT, 'dbg-legacy.png') });
  await browser.close();
})();
