var current = 'en';

export function getLang() { return current; }
export function setLang(code) {
  current = S[code] ? code : 'en';
  return current;
}
export function hasLang(code) { return !!S[code]; }

// t('key', {name: 'x'}): the text in the current language (English if missing).
export function t(key, vars) {
  var s = S[current][key];
  if (s == null) s = S.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? String(vars[k]) : m; });
  return s;
}

// Counted text: tn('cat.count', 3) uses 'cat.count.one' for 1, '.zero' for 0 if
// there is one, else '.other'.
export function tn(key, n, vars) {
  var v = Object.assign({ n: n }, vars || {});
  if (n === 0 && (S[current][key + '.zero'] != null || S.en[key + '.zero'] != null)) return t(key + '.zero', v);
  return t(key + (n === 1 ? '.one' : '.other'), v);
}

// A tag value (shape, colour, who it's for, rim) in the current language.
export function tagLabel(value) {
  if (!value) return '';
  var k = 'tag.' + value;
  if (S[current][k] != null || S.en[k] != null) return t(k);
  return value.charAt(0).toUpperCase() + value.slice(1);
}
// The same, as the word before "frame" in a generated name.
export function tagAdjective(value) {
  if (S[current]['adj.' + value] != null) return S[current]['adj.' + value];
  return tagLabel(value);
}
// Every language's label for a tag (so a search typed in any language finds it).
export function tagLabelsAll(value) {
  if (!value) return [];
  return Object.keys(S).map(function (code) { return S[code]['tag.' + value]; }).filter(Boolean);
}

// Static text in the page: elements with data-i18n="key" get their text;
// data-i18n-attr="placeholder:key, aria-label:key2" sets attributes.
export function applyStatic(root) {
  (root || document).querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
  (root || document).querySelectorAll('[data-i18n-attr]').forEach(function (el) {
    el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
      var bits = pair.split(':');
      if (bits.length === 2) el.setAttribute(bits[0].trim(), t(bits[1].trim()));
    });
  });
}

